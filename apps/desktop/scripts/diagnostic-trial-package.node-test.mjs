test('Runtime-generated bytecode fingerprint permits a second launch while every other drift still refuses', t => {
  const runtimeRoot = fs.mkdtempSync(path.join(os.tmpdir(), 'apex-diagnostic-runtime-clean-'))
  t.after(() => fs.rmSync(runtimeRoot, { force: true, recursive: true }))

  const git = args =>
    execFileSync('git', ['-C', runtimeRoot, ...args], {
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'pipe']
    })

  git(['init', '--quiet'])
  fs.writeFileSync(path.join(runtimeRoot, 'tracked.py'), 'value = 1\n')
  git(['add', 'tracked.py'])
  git(['-c', 'user.name=APEX Test', '-c', 'user.email=apex-test.invalid', 'commit', '--quiet', '-m', 'fixture'])

  assert.doesNotThrow(() => assertDiagnosticRuntimeClean(runtimeRoot))

  // The first real Runtime process records this source-checkout cache. The
  // launcher must accept the same exact checkout on its second invocation.
  fs.writeFileSync(path.join(runtimeRoot, '.bytecode-fingerprint'), `git:HEAD:${git(['rev-parse', 'HEAD']).trim()}`)
  assert.doesNotThrow(() => assertDiagnosticRuntimeClean(runtimeRoot))
  assert.doesNotThrow(() => assertDiagnosticRuntimeClean(runtimeRoot))

  fs.writeFileSync(path.join(runtimeRoot, 'tracked.py'), 'value = 2\n')
  assert.throws(() => assertDiagnosticRuntimeClean(runtimeRoot), / M tracked\.py/)

  fs.writeFileSync(path.join(runtimeRoot, 'tracked.py'), 'value = 1\n')
  fs.writeFileSync(path.join(runtimeRoot, 'unknown-cache'), 'not approved\n')
  assert.throws(() => assertDiagnosticRuntimeClean(runtimeRoot), /\?\? unknown-cache/)

  fs.rmSync(path.join(runtimeRoot, 'unknown-cache'))
  fs.rmSync(path.join(runtimeRoot, '.bytecode-fingerprint'))
  fs.symlinkSync('tracked.py', path.join(runtimeRoot, '.bytecode-fingerprint'))
  assert.throws(() => assertDiagnosticRuntimeClean(runtimeRoot), /regular non-symlink file/)

  fs.rmSync(path.join(runtimeRoot, '.bytecode-fingerprint'))
  fs.writeFileSync(path.join(runtimeRoot, '.bytecode-fingerprint'), 'not-a-runtime-fingerprint')
  assert.throws(() => assertDiagnosticRuntimeClean(runtimeRoot), /does not contain a Git checkout fingerprint/)

  fs.rmSync(path.join(runtimeRoot, '.bytecode-fingerprint'))
  fs.writeFileSync(path.join(runtimeRoot, '.bytecode-fingerprint'), 'first\n')
  git(['add', '.bytecode-fingerprint'])
  git(['-c', 'user.name=APEX Test', '-c', 'user.email=apex-test.invalid', 'commit', '--quiet', '-m', 'track stamp'])
  fs.writeFileSync(path.join(runtimeRoot, '.bytecode-fingerprint'), `git:HEAD:${'f'.repeat(40)}`)
  assert.throws(() => assertDiagnosticRuntimeClean(runtimeRoot), / M \.bytecode-fingerprint/)
})

test('the Runtime cache allowlist is exact and tied to the Runtime-owned generator', () => {
  assert.equal(GENERATED_RUNTIME_CACHE_STATUS, '?? .bytecode-fingerprint')
  assert.equal(GENERATED_RUNTIME_FINGERPRINT.test(`git:HEAD:${'a'.repeat(40)}`), true)
  assert.equal(GENERATED_RUNTIME_FINGERPRINT.test(`git:refs/heads/feature/test:${'b'.repeat(40)}`), true)
  assert.equal(GENERATED_RUNTIME_FINGERPRINT.test('git:refs/heads/feature/test:unresolved'), true)
  assert.equal(GENERATED_RUNTIME_FINGERPRINT.test('not-a-runtime-fingerprint'), false)
  assert.equal(unexpectedRuntimeStatusEntry(`${GENERATED_RUNTIME_CACHE_STATUS}\0`), null)
  assert.equal(
    unexpectedRuntimeStatusEntry(`${GENERATED_RUNTIME_CACHE_STATUS}\0?? nested/.bytecode-fingerprint\0`),
    '?? nested/.bytecode-fingerprint'
  )
  assert.equal(
    unexpectedRuntimeStatusEntry(' M .bytecode-fingerprint\0'),
    ' M .bytecode-fingerprint'
  )

  const runtimeSource = readFileSync(new URL('../../../hermes_cli/main.py', import.meta.url), 'utf8')
  assert.match(runtimeSource, /_BYTECODE_FINGERPRINT_FILE = "\.bytecode-fingerprint"/)
  assert.match(runtimeSource, /tmp_path\.write_text\(fingerprint, encoding="utf-8"\)/)
})

test('launcher and main binding probes resolve the module without importing Runtime state', () => {
  const launcherSource = readFileSync(new URL('./launch-diagnostic-trial.mjs', import.meta.url), 'utf8')
  const mainSource = readFileSync(new URL('../electron/main.ts', import.meta.url), 'utf8')
  const launcherProbe = launcherSource.slice(
    launcherSource.indexOf('function probePythonBinding('),
    launcherSource.indexOf('\nfunction main()')
  )
  const mainProbe = mainSource.slice(
    mainSource.indexOf('function readDiagnosticRuntimeBinding('),
    mainSource.indexOf('\n// The package-embedded policy')
  )

  for (const probe of [launcherProbe, mainProbe]) {
    assert.match(probe, /importlib\.util\.find_spec\('hermes_cli\.main'\)/)
    assert.doesNotMatch(probe, /import_module|HERMES_HOME/)
  }
})

test('the real Python module-spec probe does not import main or seed HERMES_HOME', t => {
  const probeHome = fs.mkdtempSync(path.join(os.tmpdir(), 'apex-diagnostic-binding-probe-'))
  t.after(() => fs.rmSync(probeHome, { force: true, recursive: true }))

  const runtimeRoot = fileURLToPath(new URL('../../..', import.meta.url))
  const python = process.env.PYTHON || (process.platform === 'win32' ? 'python' : 'python3')
  const source = [
    'import importlib.util, json, sys',
    "spec = importlib.util.find_spec('hermes_cli.main')",
    "print(json.dumps({'modulePath': spec.origin if spec else None, 'targetImported': 'hermes_cli.main' in sys.modules}))"
  ].join('; ')

  let stdout

  try {
    stdout = execFileSync(python, ['-B', '-c', source], {
      encoding: 'utf8',
      env: {
        ...process.env,
        HERMES_HOME: probeHome,
        PYTHONDONTWRITEBYTECODE: '1',
        PYTHONNOUSERSITE: '1',
        PYTHONPATH: runtimeRoot
      },
      stdio: ['ignore', 'pipe', 'pipe']
    })
  } catch (error) {
    if (error?.code === 'ENOENT') {
      t.skip(`${python} is unavailable on this packaging-test host`)

      return
    }

    throw error
  }

  const result = JSON.parse(stdout.trim())

  assert.equal(result.targetImported, false)
  assert.equal(fs.realpathSync(result.modulePath), fs.realpathSync(path.join(runtimeRoot, 'hermes_cli', 'main.py')))
  assert.deepEqual(fs.readdirSync(probeHome), [])
})

